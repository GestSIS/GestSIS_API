    private function seedDotations(): void
    {
        $typesByDesignation = DB::table('materiel_types')
            ->join('materiel_categories', 'materiel_categories.id', '=', 'materiel_types.materiel_categorie_id')
            ->where('materiel_types.est_emplacement', false)
            ->get([
                'materiel_types.id',
                'materiel_types.designation',
                'materiel_types.prefix',
                'materiel_types.est_numerote',
                'materiel_types.est_perimable',
                'materiel_categories.designation as categorie',
            ])
            ->keyBy('designation');

        mt_srand(20261119);
        $numeroParPrefix = [];
        $rows = [];
        foreach (self::DOTATION_PAR_EMPLACEMENT as $dotationEmplacementId => $dotation) {
            $emplacementParCategorie = $this->rangement($dotationEmplacementId, self::RANGEMENTS[$dotation] ?? []);
            foreach (self::DOTATIONS[$dotation] as $designation => $quantite) {
                $type = $typesByDesignation->get($designation)
                    ?? throw new RuntimeException("Type de matériel inconnu dans la dotation « {$dotation} » : {$designation}");
                $emplacementId = $emplacementParCategorie[$type->categorie] ?? $dotationEmplacementId;

                for ($piece = 0; $piece < $quantite; $piece++) {
                    $numero = '';
                    if ($type->est_numerote) {
                        $numeroParPrefix[$type->prefix] = ($numeroParPrefix[$type->prefix] ?? 0) + 1;
                        $numero = sprintf('%s-%03d', $type->prefix, $numeroParPrefix[$type->prefix]);
                    }

                    $rows[] = [
                        'materiel_type_id' => $type->id,
                        'emplacement_id' => $emplacementId,
                        'uuid' => (string) Str::uuid(),
                        'numero' => $numero,
                        'taille' => '',
                        'remarque' => '',
                        'est_etiquete' => $type->est_numerote,
                        'achat' => '',
                        'date_peremption' => $type->est_perimable ? now()->addDays(mt_rand(-90, 1095))->toDateString() : null,
                        'created_at' => '2025-01-01',
                    ];
                }
            }
        }

        foreach (array_chunk($rows, 500) as $chunk) {
            DB::table('articles')->insert($chunk);
        }
    }

