     * @return array<string, int> id du sous-emplacement, indexé par désignation de catégorie
     */
    private function rangement(int $vehiculeEmplacementId, array $rangement): array
    {
        $emplacementParCategorie = [];
        foreach ($rangement as $sousEmplacement => $categories) {
            $sousEmplacementId = DB::table('emplacements')
                ->where('parent_id', $vehiculeEmplacementId)
                ->where('designation', $sousEmplacement)
                ->soleValue('id');
            foreach ($categories as $categorie) {
                if (!DB::table('materiel_categories')->where('designation', $categorie)->exists()) {
                    throw new RuntimeException("Catégorie inconnue dans le rangement de « {$sousEmplacement} » : {$categorie}");
                }
                $emplacementParCategorie[$categorie] = $sousEmplacementId;
            }
        }

        return $emplacementParCategorie;
    }
}
